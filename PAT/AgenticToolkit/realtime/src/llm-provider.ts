/**
 * Fast-tier LLM provider abstraction. Sits between the four front-mind
 * call sites (banter-ack, banter-render, banter-narration, request-layer)
 * and the actual model API. Lets us swap Anthropic Haiku ↔ OpenRouter-
 * routed Llama 3.3 70B (Groq backend) ↔ Cerebras direct without
 * touching call-site code.
 *
 * Env shape (model-primary; provider implied by slug prefix):
 *   FAST_MODEL=anthropic/claude-haiku-4-5-20251001         # default
 *   FAST_MODEL=meta-llama/llama-3.3-70b-instruct           # OpenRouter target
 *   FAST_MODEL=cerebras/gpt-oss-120b                       # Cerebras target
 *   NARRATION_MODEL=... BANTER_ACK_MODEL=... etc.          # per-layer
 *   FAST_PROVIDER=openrouter                               # rare routing override
 *
 * Slug → provider mapping:
 *   - `anthropic/<id>`                          → AnthropicFastProvider(<id>)
 *   - `cerebras/<id>`                           → CerebrasFastProvider(<id>)
 *   - `meta-llama/...` / `mistralai/...` /      → OpenRouterFastProvider(slug)
 *     `qwen/...` / `openai/...` / ...             with provider.only=["Groq"]
 *   - unknown prefix                            → OpenRouter (default routing)
 *
 * `FAST_PROVIDER` is a routing override only — it forces the resolved
 * model through the named provider regardless of the slug's prefix. Use
 * sparingly (e.g. to force `anthropic/claude-haiku-4-5` through
 * OpenRouter for an A/B). Don't lean on it for normal operation.
 *
 * Three implementations:
 *   - AnthropicFastProvider — wraps @anthropic-ai/sdk's messages.create
 *     and messages.stream.
 *   - OpenRouterFastProvider — raw fetch against
 *     https://openrouter.ai/api/v1/chat/completions, OpenAI-compatible
 *     wire format, pins upstream to Groq via `provider.only=["Groq"]`.
 *   - CerebrasFastProvider — wraps the official
 *     `@cerebras/cerebras_cloud_sdk` Node SDK. SDK uses node-fetch with
 *     a stable agentkeepalive HTTPS agent (per its README: "reuses TCP
 *     connections to shave ~100ms off most requests") and warms a
 *     `/models` TCP connection in the client constructor. Drops
 *     `delta.reasoning` SSE chunks (CoT, not speakable). Per-model
 *     `reasoning_effort`: `'none'` for `zai-glm-4.7` (fully disable
 *     CoT), `'low'` for other reasoning models; non-reasoning models
 *     ignore the field. NOTE: SDK rides node-fetch, NOT undici, so the
 *     `diagnostics_channel` instrumentation in
 *     `llm-http-instrumentation.ts` does NOT observe these calls —
 *     `connection_reused` and `connect_ms` are intentionally absent on
 *     `provider:'cerebras'` `llm.call` events. Distinguishable from the
 *     prior raw-fetch path via `upstream_provider:'cerebras-sdk'`.
 *
 * Fallback chain (FallbackProvider) tries primary; on 5xx/timeout/network
 * error retries against fallback. Emits `kind:'llm.provider-fallback'`
 * structured-log event. Single retry per call (no cascading chain).
 * Streaming layers disable fallback by default — a partial stream
 * followed by a retry would manifest as audible double-utterance.
 *
 * See plans/front-mind-llm-swap.md for the substrate decision and
 * benchmark numbers backing it.
 */
import https from 'node:https';

import Anthropic from '@anthropic-ai/sdk';
import Cerebras from '@cerebras/cerebras_cloud_sdk';

import { markCallStart, markCallEnd } from './llm-http-instrumentation.js';

// ───────────────── HTTP instrumentation ─────────────────
//
// CRITICAL HISTORY (do not re-add `dispatcher: httpAgent` without
// fixing the undici version mismatch first):
//
// We attempted to pass a userland-undici Agent (`new Agent({...})` from
// the npm `undici@8.x` package) as the `dispatcher` option to Node's
// global `fetch()`. Verified-in-prod symptom (2026-05-23): every
// OpenRouter call threw "fetch failed" instantly because Node 22's
// built-in fetch uses undici v6.24.1 and rejects a v8.x Agent — the
// internal Agent class identity check fails.
//
// The OpenRouterFastProvider.stream catch block then returned
// `ok:false`, the FallbackProvider routed silently to Anthropic Haiku,
// and `llm.call` logs labeled the call `meta-llama/llama-3.3-70b-
// instruct` (the failed primary's model name) while the response was
// actually generated by Haiku.
//
// Fix: don't pass `dispatcher`. Node's built-in undici handles
// keep-alive on its own — back-to-back calls to the same host reuse
// the socket without us doing anything. To still get per-call
// `connection_reused` + `connect_ms` instrumentation we subscribe to
// undici's `diagnostics_channel` events (see `llm-http-instrumentation.ts`).
// That works with the built-in fetch regardless of which undici
// version Node bundles.

/** Layer identifier — drives per-layer env var resolution. */
export type FastLlmLayer =
  | 'banter-ack'
  | 'banter-render'
  | 'banter-narration'
  | 'request-layer'
  | 'banter-dispatch'
  | 'error-surfacing';

export type FastLlmProviderName = 'anthropic' | 'openrouter' | 'cerebras';

export interface FastLlmCallArgs {
  /** System prompt (cacheable per layer). */
  system: string;
  /** User message. */
  user: string;
  /** Max output tokens. */
  maxTokens: number;
  /** 'json' enables provider's JSON-object response mode. */
  responseFormat?: 'text' | 'json';
  /** Cancel signal — providers should abort the underlying HTTP request. */
  signal?: AbortSignal;
}

export interface FastLlmStreamArgs extends FastLlmCallArgs {
  /** Fired per text delta as the model emits it. `seq` 0-indexed. */
  onDelta: (text: string, seq: number) => void;
}

export interface FastLlmResult {
  /** Final model text. Null on failure (no key, sdk error, empty content). */
  text: string | null;
  /** True if the call landed content. False on every failure path. */
  ok: boolean;
  /** Failure reason when !ok. */
  error?: string;
  /** Total wall-time including stream completion. */
  latencyMs: number;
  /** Time from call start to first response signal (headers for raw
   *  fetch / first stream event for SDK). High `ttfbMs` with low
   *  `connectionReused` indicates we're paying a TLS+handshake cost. */
  ttfbMs?: number;
  /** True iff this call rode on a kept-alive socket. False ⇒ a fresh
   *  TCP/TLS handshake was performed. Inferred from undici's
   *  `diagnostics_channel` `beforeConnect`/`connected` events
   *  (see `llm-http-instrumentation.ts`). Absent ⇒ no prior
   *  observation of this host (typically the very first call after
   *  process start) or diagnostics channels unavailable. */
  connectionReused?: boolean;
  /** When a new connection was established during this call,
   *  how long the TCP+TLS handshake took (ms). Absent when
   *  `connectionReused === true` or when timing wasn't observed. */
  connectMs?: number;
  /** Provider that actually served the request. */
  provider: FastLlmProviderName;
  /** Model id sent to the wire. */
  model: string;
  /** Upstream backend when provider==='openrouter' (e.g. 'Groq'). */
  upstreamProvider?: string;
  /** True if the call was aborted via signal — distinguishes intentional
   *  cancel from genuine error. Callers (e.g. banter streaming) treat
   *  aborts as bargein rather than circuit-breaker failures. */
  aborted?: boolean;
  /** Token counts when reported. */
  usage?: { inputTokens: number; outputTokens: number };
  /** Combined size of system + user message as sent, in CHARACTERS
   *  (not tokens). Always present — providers compute it locally
   *  before the call. Useful for spotting prompt growth without
   *  waiting for the model's `usage.prompt_tokens` to land in the
   *  response (which arrives at end-of-stream, not start). */
  promptChars?: number;
}

export interface FastLlmProvider {
  readonly name: FastLlmProviderName;
  readonly model: string;
  /** Streaming call. onDelta fires per chunk; resolves with the full
   *  assembled text. The only method — callers who want the
   *  "wait till complete" shape use `awaitFullResponse(provider, args)`. */
  stream(args: FastLlmStreamArgs): Promise<FastLlmResult>;
}

/** Convenience wrapper for callers that don't care about deltas
 *  (e.g. request-layer parses JSON at completion). Equivalent to
 *  calling `provider.stream({ ...args, onDelta: () => {} })`. */
export function awaitFullResponse(
  provider: FastLlmProvider,
  args: FastLlmCallArgs,
): Promise<FastLlmResult> {
  return provider.stream({ ...args, onDelta: () => {} });
}

export type AwaitJsonResult<T> =
  | { ok: true; data: T; raw: FastLlmResult }
  | { ok: false; error: string; raw: FastLlmResult };

/** Call the provider with `responseFormat:'json'`, parse the
 *  response text as JSON, return the parsed object.
 *
 *  Parses defensively: strips ```json fences, extracts the first
 *  '{' through last '}', repairs trailing commas. Handles the cases
 *  where Anthropic prepends prose to JSON output despite the prompt;
 *  OpenRouter with response_format=json_object usually returns clean
 *  JSON, but the loose parse is a no-op in that case so no harm.
 *
 *  Shape validation is the caller's responsibility — this returns
 *  `data: T` typed by the caller, no schema enforcement here. */
export async function awaitJson<T = unknown>(
  provider: FastLlmProvider,
  args: Omit<FastLlmCallArgs, 'responseFormat'>,
): Promise<AwaitJsonResult<T>> {
  const raw = await provider.stream({ ...args, responseFormat: 'json', onDelta: () => {} });
  if (!raw.ok || raw.text === null) {
    return { ok: false, error: raw.error ?? 'no content', raw };
  }
  const parsed = parseLooseJson(raw.text);
  if (parsed === undefined) {
    return { ok: false, error: 'unparseable JSON', raw };
  }
  return { ok: true, data: parsed as T, raw };
}

/** Strict-then-loose JSON parse. Returns undefined on total failure.
 *  Loose mode strips ```json fences, extracts braces, repairs
 *  trailing commas. */
function parseLooseJson(raw: string): unknown | undefined {
  const trimmed = raw.trim();
  // Fast path — strict parse on the whole string.
  try {
    return JSON.parse(trimmed);
  } catch {
    // fallthrough
  }
  const stripped = trimmed.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '');
  const first = stripped.indexOf('{');
  const last = stripped.lastIndexOf('}');
  if (first < 0 || last <= first) return undefined;
  const candidate = stripped.slice(first, last + 1);
  try {
    return JSON.parse(candidate);
  } catch {
    try {
      return JSON.parse(candidate.replace(/,(\s*[}\]])/g, '$1'));
    } catch {
      return undefined;
    }
  }
}

// ───────────────── Anthropic implementation ─────────────────

let _anthropicClient: Anthropic | null = null;
function anthropicClient(): Anthropic {
  if (!_anthropicClient) {
    // Threading the shared undici Agent dispatcher into the Anthropic
    // SDK via a custom fetch wrapper broke the SDK's HTTP path with
    // "Connection error" — empirically reproduced 2026-05-23: every
    // banter:ack + request-layer call returned ok=false with
    // error="sdk error: Connection error." (caught Pat saying
    // "my front-mind isn't quite there" in dev). Likely an
    // interaction between SDK stream handling and our wrapper that
    // would need a proper integration. Reverted to default fetch;
    // connection_reused stays undefined for Anthropic in `llm.call`
    // events until we ship a working dispatcher integration.
    _anthropicClient = new Anthropic();
  }
  return _anthropicClient;
}

class AnthropicFastProvider implements FastLlmProvider {
  readonly name = 'anthropic' as const;
  constructor(readonly model: string) {}

  async stream(args: FastLlmStreamArgs): Promise<FastLlmResult> {
    const t0 = Date.now();
    const promptChars = args.system.length + args.user.length;
    if (!process.env.ANTHROPIC_API_KEY) {
      return { text: null, ok: false, error: 'no API key', latencyMs: 0, provider: 'anthropic', model: this.model, promptChars };
    }
    if (args.signal?.aborted) {
      return { text: null, ok: false, aborted: true, error: 'aborted before call', latencyMs: 0, provider: 'anthropic', model: this.model, promptChars };
    }
    let seq = 0;
    let accum = '';
    let stream: ReturnType<typeof anthropicClient.prototype.messages.stream> | null = null;
    let ttfbMs: number | undefined;
    // connectionReused stays undefined for Anthropic — see anthropicClient()
    // comment. The shared undici Agent dispatcher isn't wired in here.
    try {
      stream = anthropicClient().messages.stream(
        {
          model: this.model,
          max_tokens: args.maxTokens,
          system: args.system,
          messages: [{ role: 'user', content: args.user }],
        },
        args.signal ? { signal: args.signal } : undefined,
      );
      stream.on('text', (delta: string) => {
        if (ttfbMs === undefined) ttfbMs = Date.now() - t0;
        accum += delta;
        args.onDelta(delta, seq);
        seq += 1;
      });
      const finalMessage = await stream.finalMessage();
      const block = finalMessage.content.find((b: { type: string }) => b.type === 'text');
      const latencyMs = Date.now() - t0;
      if (!block || block.type !== 'text') {
        return { text: null, ok: false, error: 'no text block', latencyMs, ttfbMs, provider: 'anthropic', model: this.model, promptChars };
      }
      return {
        text: block.text,
        ok: true,
        latencyMs,
        ttfbMs,
        provider: 'anthropic',
        model: this.model,
        usage: finalMessage.usage
          ? { inputTokens: finalMessage.usage.input_tokens, outputTokens: finalMessage.usage.output_tokens }
          : undefined,
        promptChars,
      };
    } catch (err) {
      const e = err as Error;
      const aborted = e?.name === 'AbortError' || args.signal?.aborted === true;
      return {
        text: accum || null,
        ok: false,
        aborted,
        error: aborted ? 'aborted' : `sdk error: ${e.message}`,
        latencyMs: Date.now() - t0,
        ttfbMs,
        provider: 'anthropic',
        model: this.model,
        promptChars,
      };
    } finally {
      if (stream && !stream.closed && args.signal?.aborted) {
        try { stream.abort(); } catch { /* ignore */ }
      }
    }
  }
}

// ───────────────── OpenRouter implementation ─────────────────

const OPENROUTER_BASE = 'https://openrouter.ai/api/v1/chat/completions';
const OPENROUTER_HOST = 'openrouter.ai';

interface OpenRouterFastProviderOpts {
  /** Model slug, e.g. "meta-llama/llama-3.3-70b-instruct". */
  model: string;
  /** Upstream providers to pin (defaults to ["Groq"]). */
  upstreamOnly?: readonly string[];
}

class OpenRouterFastProvider implements FastLlmProvider {
  readonly name = 'openrouter' as const;
  readonly model: string;
  private readonly upstreamOnly: readonly string[];

  constructor(opts: OpenRouterFastProviderOpts) {
    this.model = opts.model;
    this.upstreamOnly = opts.upstreamOnly ?? ['Groq'];
  }

  private buildBody(args: FastLlmCallArgs): Record<string, unknown> {
    const body: Record<string, unknown> = {
      model: this.model,
      max_tokens: args.maxTokens,
      stream: true,
      messages: [
        { role: 'system', content: args.system },
        { role: 'user', content: args.user },
      ],
      provider: { only: this.upstreamOnly },
    };
    if (args.responseFormat === 'json') body.response_format = { type: 'json_object' };
    return body;
  }

  private headers(): Record<string, string> {
    const key = process.env.OPENROUTER_API_KEY;
    if (!key) throw new Error('no OPENROUTER_API_KEY');
    return {
      Authorization: `Bearer ${key}`,
      'Content-Type': 'application/json',
      'HTTP-Referer': process.env.OPENROUTER_REFERER ?? 'https://palisaderesearch.org',
      'X-Title': process.env.OPENROUTER_APP_NAME ?? 'PAT-realtime',
    };
  }

  async stream(args: FastLlmStreamArgs): Promise<FastLlmResult> {
    const t0 = Date.now();
    const promptChars = args.system.length + args.user.length;
    if (!process.env.OPENROUTER_API_KEY) {
      return { text: null, ok: false, error: 'no OPENROUTER_API_KEY', latencyMs: 0, provider: 'openrouter', model: this.model, promptChars };
    }
    if (args.signal?.aborted) {
      return { text: null, ok: false, aborted: true, error: 'aborted before call', latencyMs: 0, provider: 'openrouter', model: this.model, promptChars };
    }
    let response: Response;
    const timingHandle = markCallStart();
    const host = OPENROUTER_HOST;
    let ttfbMs: number | undefined;
    try {
      response = await fetch(OPENROUTER_BASE, {
        method: 'POST',
        headers: this.headers(),
        body: JSON.stringify(this.buildBody(args)),
        signal: args.signal,
        // Intentionally NO `dispatcher` override — see CRITICAL HISTORY
        // comment at the top of this file.
      });
      ttfbMs = Date.now() - t0;
    } catch (err) {
      const e = err as Error;
      const aborted = e?.name === 'AbortError' || args.signal?.aborted === true;
      const timing = markCallEnd(timingHandle, host);
      return {
        text: null,
        ok: false,
        aborted,
        error: aborted ? 'aborted' : `fetch error: ${e.message}`,
        latencyMs: Date.now() - t0,
        connectionReused: timing.connectionReused,
        connectMs: timing.connectMs,
        provider: 'openrouter',
        model: this.model,
        promptChars,
      };
    }
    const timing = markCallEnd(timingHandle, host);
    const connectionReused = timing.connectionReused;
    if (!response.ok || !response.body) {
      const body = await response.text().catch(() => '');
      return {
        text: null,
        ok: false,
        error: `http ${response.status}: ${body.slice(0, 300)}`,
        latencyMs: Date.now() - t0,
        ttfbMs,
        connectionReused,
        connectMs: timing.connectMs,
        provider: 'openrouter',
        model: this.model,
        promptChars,
      };
    }

    let accum = '';
    let seq = 0;
    let upstreamProvider: string | undefined;
    let usage: { inputTokens: number; outputTokens: number } | undefined;
    const reader = response.body.getReader();
    const decoder = new TextDecoder();
    let buffer = '';
    try {
      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        buffer += decoder.decode(value, { stream: true });
        // SSE events separated by \n\n; one or more `data: ...` lines per event.
        let nl;
        while ((nl = buffer.indexOf('\n')) >= 0) {
          const line = buffer.slice(0, nl).trim();
          buffer = buffer.slice(nl + 1);
          if (!line.startsWith('data: ')) continue;
          const data = line.slice(6);
          if (data === '[DONE]') break;
          let ev: { choices?: Array<{ delta?: { content?: string } }>; provider?: string; usage?: { prompt_tokens?: number; completion_tokens?: number } };
          try {
            ev = JSON.parse(data);
          } catch {
            continue;
          }
          if (!upstreamProvider && ev.provider) upstreamProvider = ev.provider;
          if (ev.usage?.prompt_tokens !== undefined && ev.usage?.completion_tokens !== undefined) {
            usage = { inputTokens: ev.usage.prompt_tokens, outputTokens: ev.usage.completion_tokens };
          }
          const delta = ev.choices?.[0]?.delta?.content;
          if (delta) {
            accum += delta;
            args.onDelta(delta, seq);
            seq += 1;
          }
        }
      }
    } catch (err) {
      const e = err as Error;
      const aborted = e?.name === 'AbortError' || args.signal?.aborted === true;
      return {
        text: accum || null,
        ok: false,
        aborted,
        error: aborted ? 'aborted' : `stream error: ${e.message}`,
        latencyMs: Date.now() - t0,
        ttfbMs,
        connectionReused,
        connectMs: timing.connectMs,
        provider: 'openrouter',
        model: this.model,
        upstreamProvider,
        promptChars,
      };
    } finally {
      try { reader.releaseLock(); } catch { /* ignore */ }
    }

    const latencyMs = Date.now() - t0;
    if (!accum) {
      return { text: null, ok: false, error: 'no content', latencyMs, ttfbMs, connectionReused, connectMs: timing.connectMs, provider: 'openrouter', model: this.model, upstreamProvider, promptChars };
    }
    return {
      text: accum,
      ok: true,
      latencyMs,
      ttfbMs,
      connectionReused,
      connectMs: timing.connectMs,
      provider: 'openrouter',
      model: this.model,
      upstreamProvider,
      usage,
      promptChars,
    };
  }
}

// ───────────────── Cerebras implementation ─────────────────
//
// Backed by the official `@cerebras/cerebras_cloud_sdk` Node SDK (NOT
// raw fetch). The SDK uses node-fetch + an agentkeepalive HTTPS agent
// that holds sockets open across calls, eliminating the per-call
// TCP+TLS handshake cost that the prior raw-fetch implementation
// suffered. Cerebras's README: "uses a stable agent for all http/https
// requests to reuse TCP connections, eliminating many TCP & TLS
// handshakes and shaving around 100ms off most requests." Empirical
// motivation: today's bench saw `conn_ms` 400-1000ms on the majority
// of Cerebras calls — fresh TLS on every turn because Node's built-in
// undici closes idle keep-alive sockets after ~4s and our inter-turn
// gap is 8-15s.
//
// Wire shape is identical to the prior raw-fetch impl (OpenAI-compat
// chat-completions). Reasoning models (gpt-oss-120b, zai-glm-4.7) emit
// `delta.reasoning` chunks before `delta.content`. Reasoning tokens
// are NOT speakable — they're chain-of-thought — so we DROP them on
// the stream. The `reasoning_effort` knob controls how many reasoning
// tokens the model spends. zai-glm-4.7 accepts `'none'` (fully disable
// CoT — verified 2026-05-24 to avoid gpt-oss-120b's 4.3s wall-time
// outliers on 1-word answers). gpt-oss-120b only accepts
// low|medium|high; we send `'low'` (floor). Non-reasoning models
// ignore the field.
//
// Instrumentation gap (intentional): the SDK rides node-fetch, not
// undici, so the diagnostics_channel subscriber in
// `llm-http-instrumentation.ts` does NOT observe these calls.
// `connectionReused` and `connectMs` are undefined for cerebras-via-
// SDK calls. The SDK's stable agent essentially makes connection-reuse
// the constant case after the first call — the absence of these fields
// in `llm.call` events IS the signal that we're on the SDK path
// (alongside `upstream_provider: 'cerebras-sdk'`).
//
// Client is constructed once per process (lazily on first use) so the
// agentkeepalive pool is shared across all CerebrasFastProvider
// instances. Constructing per-call would defeat the pool.

/** Lazy singleton Cerebras client. Constructed on first
 *  `cerebrasClient()` call — keeps the SDK's stable HTTPS agent +
 *  warm-TCP `/models` connection alive for the process lifetime, so
 *  every front-mind call reuses the same socket pool. */
let _cerebrasClient: Cerebras | null = null;
function cerebrasClient(): Cerebras {
  if (!_cerebrasClient) {
    // Explicit https.Agent so we can tune keepAliveMsecs higher than
    // node-fetch's agentkeepalive default. 30s covers the 8-15s
    // inter-turn gap several times over, well past Node 22 undici's
    // 4s idle close (irrelevant here — we're on node-fetch — but
    // matches the keepalive pinger's expectations).
    const httpAgent = new https.Agent({
      keepAlive: true,
      keepAliveMsecs: 30_000,
      maxSockets: 16,
    });
    _cerebrasClient = new Cerebras({
      apiKey: process.env.CEREBRAS_API_KEY,
      httpAgent,
      // warmTCPConnection: true is the SDK default — sends a /models
      // request in the constructor to open the TCP socket so the first
      // real chat-completions call lands on a warm pool. Don't disable.
    });
  }
  return _cerebrasClient;
}

class CerebrasFastProvider implements FastLlmProvider {
  readonly name = 'cerebras' as const;
  readonly model: string;

  constructor(opts: { model: string }) {
    this.model = opts.model;
  }

  async stream(args: FastLlmStreamArgs): Promise<FastLlmResult> {
    const t0 = Date.now();
    const promptChars = args.system.length + args.user.length;
    if (!process.env.CEREBRAS_API_KEY) {
      return { text: null, ok: false, error: 'no CEREBRAS_API_KEY', latencyMs: 0, provider: 'cerebras', model: this.model, promptChars };
    }
    if (args.signal?.aborted) {
      return { text: null, ok: false, aborted: true, error: 'aborted before call', latencyMs: 0, provider: 'cerebras', model: this.model, promptChars };
    }
    // Per-model reasoning_effort floor — see file-level comment above.
    //  - zai-glm-4.7 supports 'none'; SDK types only declare
    //    low|medium|high, so we widen via cast (the API does accept
    //    'none' on GLM regardless of what the .d.ts says).
    //  - gpt-oss-120b only accepts low|medium|high; 'low' is the floor.
    const reasoningEffort: 'none' | 'low' = this.model === 'zai-glm-4.7' ? 'none' : 'low';

    const params: Record<string, unknown> = {
      model: this.model,
      max_tokens: args.maxTokens,
      stream: true,
      messages: [
        { role: 'system', content: args.system },
        { role: 'user', content: args.user },
      ],
      reasoning_effort: reasoningEffort,
      // include_usage on the final chunk — same shape as the prior
      // raw-fetch impl pulled out of the SSE stream.
      stream_options: { include_usage: true },
    };
    if (args.responseFormat === 'json') {
      params.response_format = { type: 'json_object' };
    }

    let ttfbMs: number | undefined;
    let accum = '';
    let seq = 0;
    let usage: { inputTokens: number; outputTokens: number } | undefined;
    let stream: AsyncIterable<unknown> & { controller?: AbortController } | null = null;

    // Forward external aborts to the SDK's stream controller.
    let abortListener: (() => void) | null = null;
    const wireAbort = (s: { controller?: AbortController }) => {
      if (!args.signal || !s.controller) return;
      abortListener = () => {
        try { s.controller?.abort(); } catch { /* ignore */ }
      };
      args.signal.addEventListener('abort', abortListener, { once: true });
    };

    try {
      // SDK's chat.completions.create returns Stream<ChatCompletionChunk>
      // when stream:true. Cast through `unknown` because the SDK's
      // overload requires a TS-literal `stream: true` to pick the
      // streaming overload; our params object can't carry that
      // discriminant. Bind to `completions` — the method uses `this`
      // internally to reach the client, so a free reference strips
      // the binding and causes "_client is undefined".
      const completions = cerebrasClient().chat.completions;
      const createFn = completions.create.bind(completions) as unknown as (
        p: Record<string, unknown>,
        o?: { signal?: AbortSignal },
      ) => Promise<AsyncIterable<unknown> & { controller?: AbortController }>;
      stream = await createFn(params, args.signal ? { signal: args.signal } : undefined);
      wireAbort(stream);

      for await (const chunkUnknown of stream) {
        const chunk = chunkUnknown as {
          choices?: Array<{ delta?: { content?: string; reasoning?: string } }>;
          usage?: { prompt_tokens?: number; completion_tokens?: number };
        };
        if (chunk.usage?.prompt_tokens !== undefined && chunk.usage?.completion_tokens !== undefined) {
          usage = { inputTokens: chunk.usage.prompt_tokens, outputTokens: chunk.usage.completion_tokens };
        }
        // Drop delta.reasoning — chain-of-thought, not speakable.
        const delta = chunk.choices?.[0]?.delta?.content;
        if (delta) {
          if (ttfbMs === undefined) ttfbMs = Date.now() - t0;
          accum += delta;
          args.onDelta(delta, seq);
          seq += 1;
        }
      }
    } catch (err) {
      const e = err as { name?: string; message?: string };
      const aborted = e?.name === 'AbortError'
        || e?.name === 'APIUserAbortError'
        || args.signal?.aborted === true;
      return {
        text: accum || null,
        ok: false,
        aborted,
        error: aborted ? 'aborted' : `sdk error: ${e.message ?? String(err)}`,
        latencyMs: Date.now() - t0,
        ttfbMs,
        provider: 'cerebras',
        model: this.model,
        upstreamProvider: 'cerebras-sdk',
        promptChars,
      };
    } finally {
      if (args.signal && abortListener) {
        try { args.signal.removeEventListener('abort', abortListener); } catch { /* ignore */ }
      }
    }

    const latencyMs = Date.now() - t0;
    if (!accum) {
      return {
        text: null,
        ok: false,
        error: 'no content',
        latencyMs,
        ttfbMs,
        provider: 'cerebras',
        model: this.model,
        upstreamProvider: 'cerebras-sdk',
        promptChars,
      };
    }
    return {
      text: accum,
      ok: true,
      latencyMs,
      ttfbMs,
      // connectionReused / connectMs intentionally absent — SDK rides
      // node-fetch, not undici; the diagnostics_channel subscriber in
      // llm-http-instrumentation.ts never fires for these calls. SDK's
      // built-in agentkeepalive holds sockets open by default, so the
      // absence of these fields IS the signal that we're on the SDK.
      provider: 'cerebras',
      model: this.model,
      upstreamProvider: 'cerebras-sdk',
      usage,
      promptChars,
    };
  }
}

