/** Optional event hook fired when primary fails and we retry the
 *  fallback. Wired to structured-log emit (`kind:'llm.provider-fallback'`)
 *  in the call-site adapters. */
export type ProviderFallbackHook = (info: {
  layer: FastLlmLayer;
  primary: FastLlmProviderName;
  fallback: FastLlmProviderName;
  primaryError: string;
  primaryLatencyMs: number;
}) => void;

// ───────────────── module-level default fallback hook ─────────────────
//
// Hosts can wire a single hook at boot via `setProviderFallbackHook(...)`
// instead of threading `{onFallback}` through every call site. If a
// per-call `getFastProvider(layer, {onFallback})` hook is supplied, the
// per-call hook wins. Existed-but-silent fallbacks shipped the dispatcher
// bug in 2026-05-23 for a full day; the default hook makes that class
// of bug loud by default — any caller of getFastProvider gets the warning
// without opting in.
let _defaultFallbackHook: ProviderFallbackHook | null = null;

/** Set a process-wide default fallback hook. Pass `null` to clear.
 *  Typical use: nanoclaw's `src/index.ts` wires one at boot that emits
 *  `kind:'llm.provider-fallback'` via the host's structured logger. */
export function setProviderFallbackHook(hook: ProviderFallbackHook | null): void {
  _defaultFallbackHook = hook;
}

/** Read the current default hook — exposed for tests. */
export function getDefaultProviderFallbackHook(): ProviderFallbackHook | null {
  return _defaultFallbackHook;
}

class FallbackProvider implements FastLlmProvider {
  readonly name: FastLlmProviderName;
  readonly model: string;
  constructor(
    private readonly primary: FastLlmProvider,
    private readonly fallback: FastLlmProvider | null,
    private readonly layer: FastLlmLayer,
    private readonly hook?: ProviderFallbackHook,
  ) {
    this.name = primary.name;
    this.model = primary.model;
  }

  private shouldFallback(r: FastLlmResult, deltasEmitted: boolean): boolean {
    if (r.ok) return false;
    if (r.aborted) return false; // user-initiated cancel, not a provider failure
    if (!this.fallback) return false;
    // No 4xx fallback — those are our request bugs, not provider downtime.
    if (r.error?.startsWith('http 4')) return false;
    if (
      r.error === 'no API key'
      || r.error === 'no OPENROUTER_API_KEY'
      || r.error === 'no CEREBRAS_API_KEY'
    ) return false;
    // No retry after any deltas have already been forwarded to the
    // caller — a fallback retry would emit the same content twice,
    // which is audible double-utterance on TTS layers. The fallback is
    // safe only when the caller hasn't seen any output yet.
    if (deltasEmitted) return false;
    return true;
  }

  async stream(args: FastLlmStreamArgs): Promise<FastLlmResult> {
    let deltasEmitted = false;
    const primary = await this.primary.stream({
      ...args,
      onDelta: (text, seq) => {
        deltasEmitted = true;
        args.onDelta(text, seq);
      },
    });
    if (!this.shouldFallback(primary, deltasEmitted)) return primary;
    const info = {
      layer: this.layer,
      primary: this.primary.name,
      fallback: this.fallback!.name,
      primaryError: primary.error ?? 'unknown',
      primaryLatencyMs: primary.latencyMs,
    };
    // Per-call hook (if wired) takes precedence; otherwise fall back to
    // the module-level default. Both can fire if the call site wired one
    // AND a default is set — that's fine, hooks are observers not gates.
    try { this.hook?.(info); } catch { /* observer must not break call */ }
    if (!this.hook) {
      try { _defaultFallbackHook?.(info); } catch { /* same */ }
    }
    return this.fallback!.stream(args);
  }
}

