/** Default slug when neither `${LAYER}_MODEL` nor `FAST_MODEL` is set. */
const DEFAULT_FAST_MODEL_SLUG = 'anthropic/claude-haiku-4-5-20251001';

/** Request-layer's distinct default — Sonnet on the Anthropic side. */
const DEFAULT_REQUEST_LAYER_MODEL_SLUG = 'anthropic/claude-sonnet-4-6';

/** Env var that holds the per-layer model slug, when present. */
const LAYER_ENV: Record<FastLlmLayer, string> = {
  'banter-ack': 'BANTER_ACK_MODEL',
  'banter-render': 'BANTER_RENDER_MODEL',
  'banter-narration': 'NARRATION_MODEL',
  'request-layer': 'REQUEST_LAYER_MODEL',
  'banter-dispatch': 'BANTER_DISPATCH_MODEL',
  'error-surfacing': 'ERROR_SURFACING_MODEL',
};

/** Result of slug→routing inference. */
export interface FastModelRouting {
  /** Provider implied by the slug prefix. */
  provider: FastLlmProviderName;
  /**
   * Model id to send on the wire.
   *
   * - Anthropic: the portion AFTER the `anthropic/` prefix
   *   (e.g. `anthropic/claude-haiku-4-5` → `claude-haiku-4-5`).
   * - OpenRouter: the full slug as given (e.g.
   *   `meta-llama/llama-3.3-70b-instruct` — OpenRouter wants the full
   *   `vendor/model` slug).
   */
  model: string;
  /** Original slug pre-routing (for log metadata). */
  slug: string;
}

/** Parse a model slug into routing info.
 *
 *  - `anthropic/<id>`                → AnthropicFastProvider(<id>)
 *  - `cerebras/<id>`                 → CerebrasFastProvider(<id>)
 *  - `meta-llama/...` / `qwen/...` / → OpenRouterFastProvider(<slug>)
 *    `mistralai/...` / `openai/...` /
 *    any other `vendor/...` form
 *  - bare id (no slash) → treated as Anthropic (legacy single-segment ids
 *    e.g. `claude-haiku-4-5-20251001` keep working). */
export function parseFastModelSlug(slug: string): FastModelRouting {
  const trimmed = slug.trim();
  if (trimmed.toLowerCase().startsWith('anthropic/')) {
    return { provider: 'anthropic', model: trimmed.slice('anthropic/'.length), slug: trimmed };
  }
  if (trimmed.toLowerCase().startsWith('cerebras/')) {
    return { provider: 'cerebras', model: trimmed.slice('cerebras/'.length), slug: trimmed };
  }
  if (!trimmed.includes('/')) {
    // Single-segment id — treat as Anthropic for backwards compat with
    // bare Haiku ids that predated the slug convention.
    return { provider: 'anthropic', model: trimmed, slug: trimmed };
  }
  // Any other vendor prefix → OpenRouter, pass through the full slug.
  return { provider: 'openrouter', model: trimmed, slug: trimmed };
}

/** Resolve the model slug for a layer, honoring per-layer override
 *  (`${LAYER}_MODEL`) before global `FAST_MODEL`, with `request-layer`
 *  carrying a distinct default. */
function resolveModelSlug(layer: FastLlmLayer): string {
  const perLayer = process.env[LAYER_ENV[layer]];
  if (perLayer && perLayer.trim() !== '') return perLayer;
  if (layer === 'request-layer') {
    return process.env.FAST_MODEL ?? DEFAULT_REQUEST_LAYER_MODEL_SLUG;
  }
  return process.env.FAST_MODEL ?? DEFAULT_FAST_MODEL_SLUG;
}

/** Build a provider for a known provider name + model id. Does NOT add
 *  fallback. Exposed for tests. */
export function makeProvider(name: FastLlmProviderName, model: string): FastLlmProvider {
  if (name === 'openrouter') {
    return new OpenRouterFastProvider({ model });
  }
  if (name === 'cerebras') {
    return new CerebrasFastProvider({ model });
  }
  return new AnthropicFastProvider(model);
}

/** Resolve the provider for a given call site.
 *
 *  Reads `${LAYER}_MODEL` (per-layer) then `FAST_MODEL` (global), defaulting
 *  to `anthropic/claude-haiku-4-5-20251001` (or `anthropic/claude-sonnet-4-6`
 *  for `request-layer`). The slug prefix determines the provider. The rare
 *  `FAST_PROVIDER` env override forces routing through a named provider
 *  regardless of slug prefix.
 *
 *  When the resolved provider is NOT the Anthropic default, wraps in
 *  FallbackProvider so a provider outage degrades to the Anthropic
 *  default. Streaming calls bypass fallback after any delta has been
 *  emitted (see FallbackProvider.shouldFallback). */
export function getFastProvider(layer: FastLlmLayer, opts?: { onFallback?: ProviderFallbackHook }): FastLlmProvider {
  const slug = resolveModelSlug(layer);
  const routing = parseFastModelSlug(slug);

  // FAST_PROVIDER is a rare routing override. When set, force the
  // resolved model through that provider. Slug's implied provider is
  // ignored, but the model id (post-prefix-strip for anthropic, full
  // slug for openrouter) is kept.
  const forcedName = (process.env.FAST_PROVIDER ?? '').toLowerCase();
  let primaryName: FastLlmProviderName = routing.provider;
  if (forcedName === 'anthropic') primaryName = 'anthropic';
  else if (forcedName === 'openrouter') primaryName = 'openrouter';
  else if (forcedName === 'cerebras') primaryName = 'cerebras';

  // Anthropic only accepts bare model ids. If routing.provider was
  // openrouter, the model is a vendor/<id> slug — pass the full slug
  // straight through when we're routing to openrouter, but if a forced
  // override sends a slug-shaped model to anthropic, just hand the bare
  // id portion over (best-effort — caller's responsibility to set a
  // sensible model when forcing the override). Cerebras wants bare ids
  // (e.g. `gpt-oss-120b`); parseFastModelSlug already strips the prefix.
  let model = routing.model;
  if (primaryName === 'anthropic' && model.includes('/')) {
    model = model.slice(model.indexOf('/') + 1);
  }
  if (primaryName === 'openrouter' && !model.includes('/')) {
    // OpenRouter expects vendor/model. If the slug was a bare anthropic id,
    // route it as anthropic/<id> through OpenRouter's catalog.
    model = `anthropic/${model}`;
  }
  if (primaryName === 'cerebras' && model.includes('/')) {
    // Cerebras wants bare ids; strip any lingering vendor/ prefix.
    model = model.slice(model.indexOf('/') + 1);
  }

  const primaryProvider = makeProvider(primaryName, model);
  if (primaryName === 'anthropic') {
    return primaryProvider;
  }
  // Non-anthropic primary — wrap with anthropic fallback at the
  // layer default.
  const fallbackSlug = layer === 'request-layer'
    ? DEFAULT_REQUEST_LAYER_MODEL_SLUG
    : DEFAULT_FAST_MODEL_SLUG;
  const fallbackRouting = parseFastModelSlug(fallbackSlug);
  const fallback = makeProvider(fallbackRouting.provider, fallbackRouting.model);
  return new FallbackProvider(primaryProvider, fallback, layer, opts?.onFallback);
}

